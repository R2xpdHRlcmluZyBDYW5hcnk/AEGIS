const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const ts=require('../frontend/node_modules/typescript');
const cache={};
function load(name){
 if(cache[name])return cache[name];
 const exports={};cache[name]=exports;
 const source=fs.readFileSync('frontend/src/app/'+name+'.ts','utf8');
 const output=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
 vm.runInNewContext(output,{exports,require:relative=>load(relative.replace('./',''))});
 return exports;
}
const {mappingFromEvent,mappingFromRule,mappingFromMetadata}=load('attack-mapping');
let result=mappingFromEvent({_raw:JSON.stringify({alert:{metadata:{mitre_tactic_id:['TA0002'],mitre_technique_id:['T1059.001','T1059.001']}}})});
assert.equal(result.tactics[0].name,'Execution');
assert.equal(result.techniques.length,1);
assert.equal(result.techniques[0].name,'PowerShell');
assert.equal(result.techniques[0].url,'https://attack.mitre.org/techniques/T1059/001/');
assert.ok(result.techniques[0].description);
assert.equal(mappingFromEvent({_raw:'invalid'}).tactics.length,0);
assert.equal(mappingFromMetadata({mitre_tactic_id:['<img src=x onerror=alert(1)>','TA0011.evil']}).tactics.length,0);
result=mappingFromRule('alert http any any -> any any (msg:"metadata: mitre_tactic_id TA0040; fake"; metadata:mitre_tactic_id TA0002, mitre_technique_id T1059.001; metadata: mitre_technique_id T1568; sid:1;)');
assert.equal(result.tactics.length,1);
assert.equal(result.tactics[0].id,'TA0002');
